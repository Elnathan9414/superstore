-- =====================================================================
-- 0004: Sales / point of sale (stage 3)
-- Run in the Supabase SQL Editor AFTER 0003_products_stock.sql.
--
-- - shop_settings: address, phone, receipt footer, seller discount cap
-- - sale_item_costs: unit cost at time of sale, moved out of sale_items so
--   sellers (who can read sale_items) never see costs
-- - create_sale(): the ONLY way to record a sale. Prices come from the
--   database, totals are recomputed, stock and serial units are checked
--   under row locks, payments validated, all in one transaction.
-- - cancel_sale(): managers only; puts stock and serial units back
-- - sale_overview: sales with paid amount, balance, seller and customer
-- =====================================================================

-- ---------- Settings ----------
alter table shop_settings
  add column shop_address text,
  add column shop_phone text,
  add column receipt_footer text default 'Merci de votre visite !',
  add column seller_max_discount_percent smallint not null default 10
    check (seller_max_discount_percent between 0 and 100);

-- ---------- Sales: idempotency key and cancellation ----------
alter table sales
  -- Generated by the till for each checkout; a repeated submit (double
  -- click, network retry) returns the existing sale instead of a duplicate.
  add column client_ref uuid unique,
  add column cancelled_at timestamptz,
  add column cancelled_by uuid references profiles(id),
  add column cancel_reason text;

alter table payments add column reference text;   -- e.g. mobile money transaction id

-- ---------- Sale item costs (managers and owners only) ----------
create table sale_item_costs (
  sale_item_id bigint primary key references sale_items(id) on delete cascade,
  unit_cost bigint not null check (unit_cost >= 0)  -- cost at time of sale (for margin)
);

insert into sale_item_costs (sale_item_id, unit_cost)
select id, unit_cost from sale_items;

alter table sale_items drop column unit_cost;

alter table sale_item_costs enable row level security;
create policy "managers read sale_item_costs" on sale_item_costs
  for select to authenticated using (is_manager_or_owner());
-- No write policy: rows are only written by create_sale().

-- ---------- Sales are written through functions only ----------
drop policy if exists "staff insert sales" on sales;
drop policy if exists "managers update sales" on sales;
drop policy if exists "staff insert sale_items" on sale_items;
drop policy if exists "staff insert payments" on payments;

create index if not exists sale_items_sale_idx on sale_items (sale_id);
create index if not exists payments_sale_idx on payments (sale_id);
create index if not exists serial_units_sale_item_idx on serial_units (sale_item_id);
create index if not exists sales_customer_idx on sales (customer_id);

-- ---------- Read view ----------
create view sale_overview
with (security_invoker = true) as
select s.id,
       s.created_at,
       s.status,
       s.subtotal,
       s.discount,
       s.total,
       coalesce(pay.paid, 0)::bigint as paid,
       (s.total - coalesce(pay.paid, 0))::bigint as balance,
       s.seller_id,
       seller.full_name as seller_name,
       s.customer_id,
       c.full_name as customer_name,
       c.phone as customer_phone,
       coalesce(items.item_count, 0)::integer as item_count,
       s.notes,
       s.cancelled_at,
       canceller.full_name as cancelled_by_name,
       s.cancel_reason
from sales s
left join profiles seller on seller.id = s.seller_id
left join profiles canceller on canceller.id = s.cancelled_by
left join customers c on c.id = s.customer_id
left join (
  select sale_id, sum(amount) as paid from payments group by sale_id
) pay on pay.sale_id = s.id
left join (
  select sale_id, sum(quantity) as item_count from sale_items group by sale_id
) items on items.sale_id = s.id;

-- ---------- Create sale ----------
-- p_items:    [{"product_id": 1, "quantity": 2, "serial_ids": [10, 11]}, ...]
-- p_payments: [{"method": "cash", "amount": 5000, "reference": null}, ...]
-- p_discount_type: null | 'amount' | 'percent' (percent = whole number 0-100)
-- p_expected_total: total shown at the till; if prices changed meanwhile the
--                   sale is refused so the seller can confirm the new total.
create or replace function create_sale(
  p_client_ref uuid,
  p_customer_id bigint,
  p_items jsonb,
  p_discount_type text,
  p_discount_value bigint,
  p_payments jsonb,
  p_expected_total bigint default null,
  p_notes text default null
)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_role user_role := current_user_role();
  v_sale_id bigint;
  v_existing_seller uuid;
  v_item jsonb;
  v_payment jsonb;
  v_product products%rowtype;
  v_qty integer;
  v_serial_ids bigint[];
  v_subtotal bigint := 0;
  v_discount bigint := 0;
  v_total bigint;
  v_paid bigint := 0;
  v_cap smallint;
  v_sale_item_id bigint;
  v_cost bigint;
  v_today date := (now() at time zone 'Africa/Douala')::date;
  v_product_ids bigint[];
begin
  if v_role is null then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  -- Idempotency: same checkout submitted twice
  if p_client_ref is not null then
    select id, seller_id into v_sale_id, v_existing_seller from sales where client_ref = p_client_ref;
    if found then
      if v_existing_seller <> auth.uid() then
        raise exception 'forbidden' using errcode = '42501';
      end if;
      return v_sale_id;
    end if;
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'empty_cart';
  end if;

  select array_agg((x->>'product_id')::bigint) into v_product_ids
  from jsonb_array_elements(p_items) as x;
  if cardinality(v_product_ids) <> (select count(distinct id) from unnest(v_product_ids) as id) then
    raise exception 'duplicate_product';
  end if;

  -- Lock all products in a fixed order (avoids deadlocks between tills)
  perform 1 from products where id = any(v_product_ids) order by id for update;

  -- ----- Validate items and compute subtotal from database prices -----
  for v_item in select * from jsonb_array_elements(p_items) loop
    select * into v_product from products where id = (v_item->>'product_id')::bigint;
    if not found then
      raise exception 'product_not_found';
    end if;
    if not v_product.is_active then
      raise exception 'product_inactive' using detail = v_product.name;
    end if;

    v_qty := (v_item->>'quantity')::integer;
    if v_qty is null or v_qty <= 0 then
      raise exception 'invalid_quantity';
    end if;
    if product_stock_of(v_product.id) < v_qty then
      raise exception 'insufficient_stock' using detail = v_product.name;
    end if;

    select coalesce(array_agg(distinct x::bigint), '{}') into v_serial_ids
    from jsonb_array_elements_text(coalesce(v_item->'serial_ids', '[]'::jsonb)) as x;

    if v_product.tracks_serial then
      if cardinality(v_serial_ids) <> v_qty
         or cardinality(v_serial_ids) <> jsonb_array_length(coalesce(v_item->'serial_ids', '[]'::jsonb)) then
        raise exception 'serial_count_mismatch' using detail = v_product.name;
      end if;
      perform 1 from serial_units where id = any(v_serial_ids) order by id for update;
      if (select count(*) from serial_units
          where id = any(v_serial_ids) and product_id = v_product.id and status = 'in_stock')
         <> v_qty then
        raise exception 'serial_not_in_stock' using detail = v_product.name;
      end if;
    elsif cardinality(v_serial_ids) > 0 then
      raise exception 'serials_not_tracked' using detail = v_product.name;
    end if;

    v_subtotal := v_subtotal + v_product.sale_price * v_qty;
  end loop;

  -- ----- Discount -----
  if p_discount_type is null or coalesce(p_discount_value, 0) = 0 then
    v_discount := 0;
  elsif p_discount_type = 'amount' then
    if p_discount_value < 0 or p_discount_value > v_subtotal then
      raise exception 'invalid_discount';
    end if;
    v_discount := p_discount_value;
  elsif p_discount_type = 'percent' then
    if p_discount_value < 0 or p_discount_value > 100 then
      raise exception 'invalid_discount';
    end if;
    -- Rounded down to the smallest unit (same rule as lib/sale.ts)
    v_discount := (v_subtotal * p_discount_value) / 100;
  else
    raise exception 'invalid_discount';
  end if;

  if v_role = 'seller' then
    select seller_max_discount_percent into v_cap from shop_settings;
    if v_discount * 100 > v_subtotal * coalesce(v_cap, 0) then
      raise exception 'discount_too_high' using detail = coalesce(v_cap, 0)::text;
    end if;
  end if;

  v_total := v_subtotal - v_discount;

  if p_expected_total is not null and p_expected_total <> v_total then
    raise exception 'total_mismatch' using detail = v_total::text;
  end if;

  -- ----- Payments -----
  if p_payments is not null and jsonb_typeof(p_payments) <> 'array' then
    raise exception 'invalid_payment';
  end if;
  for v_payment in select * from jsonb_array_elements(coalesce(p_payments, '[]'::jsonb)) loop
    if (v_payment->>'amount')::bigint is null or (v_payment->>'amount')::bigint <= 0 then
      raise exception 'invalid_payment';
    end if;
    if not coalesce(v_payment->>'method', '') = any(enum_range(null::payment_method)::text[]) then
      raise exception 'invalid_payment';
    end if;
    v_paid := v_paid + (v_payment->>'amount')::bigint;
  end loop;

  if v_paid > v_total then
    raise exception 'overpayment';
  end if;
  if v_paid < v_total and p_customer_id is null then
    raise exception 'customer_required';
  end if;
  if p_customer_id is not null and not exists (select 1 from customers where id = p_customer_id) then
    raise exception 'customer_not_found';
  end if;

  -- ----- Write -----
  insert into sales (customer_id, seller_id, subtotal, discount, total, notes, client_ref)
  values (p_customer_id, auth.uid(), v_subtotal, v_discount, v_total,
          nullif(btrim(p_notes), ''), p_client_ref)
  returning id into v_sale_id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    select * into v_product from products where id = (v_item->>'product_id')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    v_cost := coalesce((select cost_price from product_costs where product_id = v_product.id), 0);

    -- The sale_item_stock_movement trigger records the stock movement
    insert into sale_items (sale_id, product_id, quantity, unit_price)
    values (v_sale_id, v_product.id, v_qty, v_product.sale_price)
    returning id into v_sale_item_id;

    insert into sale_item_costs (sale_item_id, unit_cost)
    values (v_sale_item_id, v_cost);

    if v_product.tracks_serial then
      update serial_units
      set status = 'sold',
          sale_item_id = v_sale_item_id,
          warranty_ends_at = case
            when v_product.warranty_months > 0
              then (v_today + make_interval(months => v_product.warranty_months))::date
            end
      where id in (
        select x::bigint from jsonb_array_elements_text(v_item->'serial_ids') as x
      );
    end if;
  end loop;

  insert into payments (sale_id, method, amount, reference)
  select v_sale_id,
         (x->>'method')::payment_method,
         (x->>'amount')::bigint,
         nullif(btrim(x->>'reference'), '')
  from jsonb_array_elements(coalesce(p_payments, '[]'::jsonb)) as x;

  return v_sale_id;
end;
$$;

-- ---------- Cancel sale (managers and owners) ----------
create or replace function cancel_sale(p_sale_id bigint, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_status sale_status;
begin
  if not is_manager_or_owner() then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  if nullif(btrim(p_reason), '') is null then
    raise exception 'reason_required';
  end if;

  select status into v_status from sales where id = p_sale_id for update;
  if not found then
    raise exception 'sale_not_found';
  end if;
  if v_status = 'cancelled' then
    raise exception 'already_cancelled';
  end if;

  -- Put the goods back in stock
  insert into stock_movements (product_id, quantity, type, sale_item_id, reason, created_by)
  select si.product_id, si.quantity, 'return', si.id,
         format('Annulation vente n° %s : %s', p_sale_id, btrim(p_reason)), auth.uid()
  from sale_items si
  where si.sale_id = p_sale_id;

  update serial_units
  set status = 'in_stock', sale_item_id = null, warranty_ends_at = null
  where sale_item_id in (select id from sale_items where sale_id = p_sale_id);

  update sales
  set status = 'cancelled',
      cancelled_at = now(),
      cancelled_by = auth.uid(),
      cancel_reason = btrim(p_reason)
  where id = p_sale_id;
end;
$$;

revoke execute on function create_sale(uuid, bigint, jsonb, text, bigint, jsonb, bigint, text) from public, anon;
revoke execute on function cancel_sale(bigint, text) from public, anon;
grant execute on function create_sale(uuid, bigint, jsonb, text, bigint, jsonb, bigint, text) to authenticated;
grant execute on function cancel_sale(bigint, text) to authenticated;
